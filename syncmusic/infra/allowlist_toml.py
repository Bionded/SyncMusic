"""The hardware test suite's allowlist (`tests/hardware.toml`) for registered devices, in the format
`infra/blockdev/guard.Allowlist.load` reads: one table per device with its USB serial(s) and file system UUID.

Only devices with such an identity are listed (network and folder devices have none). A serial that every unit of a
model shares (GENERIC_SERIALS) is left out - the device is matched by its file system UUID alone - so the list never
allows another unit of the same model."""

from __future__ import annotations

import json
import re

from syncmusic.core.models import DeviceConfig
from syncmusic.infra.blockdev.guard import GENERIC_SERIALS

HEADER = """\
# Hardware allowlist for the SyncMusic test suite (generated by SyncMusic).
# WARNING: the hardware tests may FORMAT, wipe and overwrite every device listed here. List only players you can
# lose the contents of. The block-device guard refuses every disk that is not listed.
"""


def _key(name: str, taken: set[str]) -> str:
    key = re.sub(r"[^a-z0-9_]+", "_", name.lower()).strip("_") or "device"
    base, n = key, 2
    while key in taken:
        key, n = f"{base}_{n}", n + 1
    taken.add(key)
    return key


def render(devices: list[DeviceConfig]) -> str:
    """The TOML text for `devices`; devices without a USB serial or file system UUID are skipped."""
    out, taken = [HEADER], set[str]()
    for d in devices:
        ident = d.identity
        serials = [s for s in ident.serials() if s not in GENERIC_SERIALS]
        if not serials and not ident.fs_uuid:
            continue
        lines = [f"\n# {d.name} ({d.type})", f"[{_key(d.id, taken)}]"]
        if serials:
            lines.append(f"usb_serial = {json.dumps(serials[0])}")
        if len(serials) > 1:
            lines.append(f"usb_serial_aliases = {json.dumps(serials[1:])}")
        if ident.fs_uuid:
            lines.append(f"fs_uuid = {json.dumps(ident.fs_uuid)}")
        lines.append(f"type = {json.dumps(d.type)}")
        out.append("\n".join(lines) + "\n")
    return "".join(out)
